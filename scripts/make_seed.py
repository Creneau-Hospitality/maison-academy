"""Build supabase/migrations/0002_seed_cards.sql from the phase-0 card export.
Run: python3 scripts/make_seed.py

The cards go in as one JSON block (one list per card, fields in the order of `keep`), so their
approvals from Phase 0 are kept (the SQL editor runs with server rights).
Cards that already exist are left alone, so it is safe to run again."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
cards = json.loads((root / 'exports/2026-10-16-phase-0/cards.json').read_text())['cards']
keep = ['id', 'track', 'unit', 'level', 'roles', 'type', 'prompt', 'media', 'options', 'answer',
        'explanation', 'why_it_matters', 'is_allergen', 'source_ref', 'review_note', 'status',
        'reviewed_by', 'reviewed_at', 'allergen_check_by', 'version']
rows = [[c.get(k) for k in keep] for c in cards]  # positional, to keep the file small
blob = json.dumps(rows, ensure_ascii=False, separators=(',', ':'))
assert '$cards$' not in blob
sql = f"""-- Maison Academy · Phase 1 · load the {len(cards)} cards drafted in Phase 0
-- Generated by scripts/make_seed.py from exports/2026-10-16-phase-0/cards.json.
insert into public.cards (id, track_id, unit_id, level, roles, type, prompt, media, options, answer,
  explanation, why_it_matters, is_allergen, source_ref, review_note, status, reviewed_by, reviewed_at,
  allergen_check_by, version, updated_by)
select e->>0, e->>1, e->>2, (e->>3)::smallint,
  array(select jsonb_array_elements_text(e->4)), e->>5, e->>6, e->>7, e->8, e->9,
  coalesce(e->>10, ''), coalesce(e->>11, ''), (e->>12)::boolean, coalesce(e->>13, ''),
  e->>14, e->>15, e->>16, (e->>17)::timestamptz, e->>18, coalesce((e->>19)::int, 1), 'Phase 0 drafts'
from jsonb_array_elements($cards${blob}$cards$::jsonb) as e
on conflict (id) do nothing;

update public.card_versions set saved_by = 'Phase 0 drafts' where saved_by = 'System' and version = 1;
update public.audit_log set actor = 'Phase 0 drafts' where actor = 'System' and action = 'card_created';

select status, is_allergen, count(*) from public.cards group by 1, 2 order by 1, 2;
"""
(root / 'supabase/migrations/0002_seed_cards.sql').write_text(sql)
print(len(cards), 'cards,', len(sql.encode()), 'bytes')
