"""Turn a content/drafts/*-cards.json file (unit + cards) into a SQL migration that adds
new cards in review. Options are stored shuffled; "put in order" cards get their steps shuffled.
Usage: python3 scripts/make_new_cards_sql.py content/drafts/service-steps-cards.json 0011_service_steps"""
import json, sys, pathlib, random
root = pathlib.Path(__file__).resolve().parent.parent
src, name = sys.argv[1], sys.argv[2]
d = json.loads((root / src).read_text())
u = d['unit']
q = lambda s: "'" + str(s).replace("'", "''") + "'"
prefix = {'service': 'svc', 'food': 'food', 'drinks': 'drk', 'sop': 'sop', 'upselling': 'up', 'suggestive': 'sug'}[u['track_id']]
rows = []
for c in d['cards']:
    opts = list(c.get('options') or c['answer'])
    assert all(a in opts for a in c['answer']), c['n']
    random.shuffle(opts)
    if c['type'] == 'order':
        while opts == c['answer']: random.shuffle(opts)
    cid = f"{prefix}-{u['id']}-{c['n']:04d}"
    rows.append("  (" + ", ".join([q(cid), q(u['track_id']), q(u['id']), str(c.get('level', 1)),
        "array[" + ",".join(q(r) for r in c['roles']) + "]::text[]", q(c['type']), q(c['prompt']),
        q(json.dumps(opts, ensure_ascii=False)) + "::jsonb", q(json.dumps(c['answer'], ensure_ascii=False)) + "::jsonb",
        q(c['explanation']), q(c['why']), 'true' if c.get('allergen') else 'false',
        q(f"{d['source']}, {c['step']}"),
        q(c.get('note') or ('Drafted by Claude ' + __import__('datetime').date.today().isoformat() + ' from ' + d['source'] + '.'
          + (' Allergen card: needs the kitchen check.' if c.get('allergen') else ''))),
        "'review'", "'Claude (draft for David)'"]) + ")")
sql = f"""-- Maison Academy · new cards: {name} ({len(rows)} cards, unit "{u['name']}")
-- Generated by scripts/make_new_cards_sql.py from {src}. All arrive in review.
insert into public.units (id, track_id, name, sort) values ({q(u['id'])}, {q(u['track_id'])}, {q(u['name'])}, {u['sort']})
on conflict (id) do nothing;

insert into public.cards (id, track_id, unit_id, level, roles, type, prompt, options, answer, explanation,
  why_it_matters, is_allergen, source_ref, review_note, status, updated_by)
values
""" + ",\n".join(rows) + """
on conflict (id) do nothing;

update public.card_versions set saved_by = 'Claude (draft for David)' where saved_by = 'System';
update public.audit_log set actor = 'Claude (draft for David)' where actor = 'System' and action = 'card_created';

""" + f"select count(*) as added, {len(rows)} as in_file from public.cards where unit_id = {q(u['id'])};\n"
(root / f'supabase/migrations/{name}.sql').write_text(sql)
print(name, len(rows), 'cards')
