"""Turn one or more content/drafts/*-cards.json files (unit + cards) into one SQL migration that adds
new cards in review. Options are stored shuffled; "put in order" cards get their steps shuffled.
A card may carry "media" (a photo path served by the app, e.g. /menu/2026-10/goulash.jpg).
Usage: python3 scripts/make_new_cards_sql.py 0024_menu_oct26 content/drafts/a-cards.json [content/drafts/b-cards.json ...]
(The older form, make_new_cards_sql.py <file> <name>, still works.)"""
import json, sys, pathlib, random, datetime
root = pathlib.Path(__file__).resolve().parent.parent
args = sys.argv[1:]
if args[0].endswith('.json'): args = [args[1], args[0]]
name, srcs = args[0], args[1:]
q = lambda s: "'" + str(s).replace("'", "''") + "'"
units, rows, counts = [], [], []
for src in srcs:
    d = json.loads((root / src).read_text())
    u = d['unit']
    prefix = {'service': 'svc', 'food': 'food', 'drinks': 'drk', 'sop': 'sop', 'upselling': 'up', 'suggestive': 'sug'}[u['track_id']]
    units.append(f"  ({q(u['id'])}, {q(u['track_id'])}, {q(u['name'])}, {u['sort']})")
    counts.append((u['id'], len(d['cards'])))
    for c in d['cards']:
        opts = list(c.get('options') or c['answer'])
        assert all(a in opts for a in c['answer']), c['n']
        random.shuffle(opts)
        if c['type'] == 'order':
            while opts == c['answer']: random.shuffle(opts)
        cid = f"{prefix}-{u['id']}-{c['n']:04d}"
        rows.append("  (" + ", ".join([q(cid), q(u['track_id']), q(u['id']), str(c.get('level', 1)),
            "array[" + ",".join(q(r) for r in c['roles']) + "]::text[]", q(c['type']), q(c['prompt']),
            q(c['media']) if c.get('media') else 'null',
            q(json.dumps(opts, ensure_ascii=False)) + "::jsonb", q(json.dumps(c['answer'], ensure_ascii=False)) + "::jsonb",
            q(c['explanation']), q(c['why']), 'true' if c.get('allergen') else 'false',
            q(f"{d['source']}, {c['step']}"),
            q(c.get('note') or ('Drafted by Claude ' + datetime.date.today().isoformat() + ' from ' + d['source'] + '.'
              + (' Allergen card: needs the kitchen check.' if c.get('allergen') else ''))),
            "'review'", "'Claude (draft for David)'"]) + ")")
sql = f"""-- Maison Academy · new cards: {name} ({len(rows)} cards)
-- Generated by scripts/make_new_cards_sql.py from {', '.join(srcs)}. All arrive in review.
insert into public.units (id, track_id, name, sort) values
""" + ",\n".join(units) + """
on conflict (id) do nothing;

insert into public.cards (id, track_id, unit_id, level, roles, type, prompt, media, options, answer, explanation,
  why_it_matters, is_allergen, source_ref, review_note, status, updated_by)
values
""" + ",\n".join(rows) + """
on conflict (id) do nothing;

update public.card_versions set saved_by = 'Claude (draft for David)' where saved_by = 'System';
update public.audit_log set actor = 'Claude (draft for David)' where actor = 'System' and action = 'card_created';

""" + "select unit_id, count(*) as cards from public.cards where unit_id in (" + ", ".join(q(u) for u, _ in counts) + ") group by unit_id order by unit_id;\n"
(root / f'supabase/migrations/{name}.sql').write_text(sql)
print(name, len(rows), 'cards', counts)
