"""Turn a content/harder/batchN_*.json file into a SQL migration.
Each entry: id -> new options list (right answer unchanged), or
{"options": [...], "answer": [...]} for pick-all cards whose right set shrinks.
Checks every entry against the Phase 0 export before writing anything.
Usage: python3 scripts/make_harder_sql.py content/harder/batch1_service.json 0007_harder_service"""
import json, sys, pathlib, random
root = pathlib.Path(__file__).resolve().parent.parent
src, name = sys.argv[1], sys.argv[2]
batch = json.loads((root / src).read_text())
cards = {c['id']: c for c in json.loads((root / 'exports/2026-10-16-phase-0/cards.json').read_text())['cards']}
q = lambda s: "'" + s.replace("'", "''") + "'"
problems, rows = [], []
for cid, v in batch.items():
    c = cards.get(cid)
    if not c: problems.append(f'{cid}: unknown card'); continue
    opts = v['options'] if isinstance(v, dict) else v
    ans = v['answer'] if isinstance(v, dict) else c['answer']
    if c['is_allergen']: problems.append(f'{cid}: allergen card, leave for the kitchen')
    if c['type'] == 'order': problems.append(f'{cid}: order card')
    if len(set(opts)) != len(opts): problems.append(f'{cid}: duplicate option')
    if not all(a in opts for a in ans): problems.append(f'{cid}: right answer missing from options')
    if not all(a in c['answer'] for a in ans): problems.append(f'{cid}: new right answer not in the original right answers')
    if c['type'] != 'multi' and len(ans) != 1: problems.append(f'{cid}: single-answer card')
    if not 2 <= len(opts) <= 6: problems.append(f'{cid}: option count')
    if any(not o.strip() for o in opts): problems.append(f'{cid}: empty option')
    longest = max(len(o) for o in opts)
    if c['type'] != 'multi' and len(ans[0]) == longest and sum(len(o) == longest for o in opts) == 1 and len(opts) > 2:
        print(f'note: {cid} right answer is still uniquely the longest')
    random.shuffle(opts)
    rows.append((cid, opts, ans, c['answer']))
if problems:
    print('\n'.join(problems)); sys.exit(1)
lines = [f"-- Maison Academy · harder wrong options: {name} ({len(rows)} cards)",
         "-- Generated by scripts/make_harder_sql.py from " + src + ".",
         "-- Same questions, facts and right answers; wrong options taken from our own menus and standards.",
         "-- Each card goes back to review. A card is only changed if it is live and its right answer still",
         "-- matches the Phase 0 export, so anything David has edited since is left alone.", "",
         "with h(id, options, answer, old_answer) as (values"]
lines.append(",\n".join(f"  ({q(cid)}, {q(json.dumps(o, ensure_ascii=False))}::jsonb, {q(json.dumps(a, ensure_ascii=False))}::jsonb, {q(json.dumps(oa, ensure_ascii=False))}::jsonb)" for cid, o, a, oa in rows) + ")")
lines += [
 "update public.cards c set options = h.options, answer = h.answer,",
 "  status = 'review', reviewed_by = null, reviewed_at = null,",
 f"  review_note = 'Harder wrong options ({name}), drafted by Claude {__import__('datetime').date.today().isoformat()}. Same facts and right answer.',",
 "  updated_by = 'Claude (draft for David)'",
 "from h where c.id = h.id and c.status = 'live' and not c.is_allergen",
 "  and public.sorted_jsonb(c.answer) = public.sorted_jsonb(h.old_answer);", "",
 "update public.card_versions set saved_by = 'Claude (draft for David)' where saved_by = 'System';",
 "update public.audit_log set actor = 'Claude (draft for David)' where actor = 'System' and action = 'card_edited';", "",
 f"select count(*) as changed, {len(rows)} as in_batch from public.cards where review_note like '%({name})%' and status = 'review';", ""]
out = root / f'supabase/migrations/{name}.sql'
out.write_text("\n".join(lines))
print(out, len(rows), 'cards')
